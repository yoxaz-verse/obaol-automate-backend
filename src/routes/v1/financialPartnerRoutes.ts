import { Router } from "express";
import authenticateToken from "../../middlewares/auth";
import { financialPartnerController as c } from "../../controllers/financialPartnerController";
const router = Router(); router.use(authenticateToken);
router.get("/portfolio", c.getPortfolio.bind(c));
router.put("/portfolio", c.savePortfolio.bind(c));
router.post("/portfolio/submit", c.submitPortfolio.bind(c));
router.get("/approvals", c.approvals.bind(c));
router.patch("/approvals/:id", c.review.bind(c));
router.get("/directory", c.directory.bind(c));
router.get("/directory/:id", c.detail.bind(c));
router.post("/directory/:id/applications", c.createApplication.bind(c));
router.get("/applications", c.applications.bind(c));
router.patch("/applications/:id/status", c.transition.bind(c));
export default router;
